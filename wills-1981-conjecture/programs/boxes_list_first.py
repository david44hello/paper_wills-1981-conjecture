# Labels such as L6 or Path C in the comments: see the glossary at the top of check_claims.py.
# Exact rational arithmetic throughout (fractions.Fraction); no floating point.
#
# A box is Pi(Gamma, a') = { (z, t) : z in [-1,1]^3, |t - a'.z| <= 1 } with lattice Gamma x Z, where
#   Gamma = a sublattice of Z^3 of index d <= 6 whose cube points C = Gamma cap {-1,0,1}^3 span R^3, and
#   a' in Lambda_z = {a : a.z_j in Z} for some independent triple z_j in C, taken modulo Gamma*, with a' NOT in Gamma*.
# Equivalences: signed permutations of z (B3, order 48) acting on (Gamma, a'); a' -> -a' (t -> -t); a' mod Gamma* (shears).
# Output: one JSON record per class with the box's lattice points in integer coordinates (w, t), z = sum w_i r_i (r_i = HNF
# rows of Gamma), so the ambient lattice is Z^4 and every o-symmetric saturated full-dimensional subset is in W_4 (claim N10).
import argparse
import itertools
import json
import sys
from fractions import Fraction as Fr
from pathlib import Path

CUBE3 = [zz for zz in itertools.product((-1, 0, 1), repeat=3)]


def hnf_bases(index):
    """All lower-triangular HNF row bases of sublattices of Z^3 with the given index."""
    out = []
    for h11 in range(1, index + 1):
        for h22 in range(1, index + 1):
            if index % (h11 * h22):
                continue
            h33 = index // (h11 * h22)
            for h21, h31 in itertools.product(range(h11), repeat=2):
                for h32 in range(h22):
                    out.append(((h11, 0, 0), (h21, h22, 0), (h31, h32, h33)))
    return out


def coords_in_basis(basis, zz):
    """Integer coordinates w with zz = sum w_i basis_i (lower-triangular basis), or None if zz is not in the lattice."""
    (h11, _, _), (h21, h22, _), (h31, h32, h33) = basis
    if zz[2] % h33:
        return None
    w3 = zz[2] // h33
    rest2 = zz[1] - w3 * h32
    if rest2 % h22:
        return None
    w2 = rest2 // h22
    rest1 = zz[0] - w2 * h21 - w3 * h31
    if rest1 % h11:
        return None
    return (rest1 // h11, w2, w3)


def cube_points(basis):
    """Gamma cap {-1,0,1}^3."""
    return [zz for zz in CUBE3 if coords_in_basis(basis, zz) is not None]


def det3(mat):
    """Exact 3x3 determinant."""
    (a, b, c), (d, e, f), (g, h, i) = mat
    return a * (e * i - f * h) - b * (d * i - f * g) + c * (d * h - e * g)


def solve3(mat, rhs):
    """Exact solution x of mat x = rhs (Cramer)."""
    den = Fr(det3(mat))
    sols = []
    for col in range(3):
        mm = [list(row) for row in mat]
        for row in range(3):
            mm[row][col] = rhs[row]
        sols.append(Fr(det3(mm)) / den)
    return tuple(sols)


def hnf(rows):
    """Lower-triangular Hermite normal form of the lattice generated by 3 integer rows (full rank): row i is zero beyond
    column i, diagonal positive, 0 <= h_ij < h_jj below the diagonal. Unimodular row operations only (exact)."""
    rows = [list(rr) for rr in rows]
    for col in (2, 1, 0):
        active = list(range(col + 1))
        while True:
            nonzero = [ii for ii in active if rows[ii][col] != 0]
            if len(nonzero) <= 1:
                break
            nonzero.sort(key=lambda ii: abs(rows[ii][col]))
            piv = nonzero[0]
            for ii in nonzero[1:]:
                qq = rows[ii][col] // rows[piv][col]
                rows[ii] = [aa - qq * bb for aa, bb in zip(rows[ii], rows[piv])]
        nonzero = [ii for ii in active if rows[ii][col] != 0]
        if len(nonzero) != 1:
            raise ValueError("rows are not of full rank")
        piv = nonzero[0]
        rows[piv], rows[col] = rows[col], rows[piv]
        if rows[col][col] < 0:
            rows[col] = [-vv for vv in rows[col]]
    for ii in (1, 2):
        for jj in range(ii - 1, -1, -1):
            qq = rows[ii][jj] // rows[jj][jj]
            rows[ii] = [aa - qq * bb for aa, bb in zip(rows[ii], rows[jj])]
    return tuple(tuple(rr) for rr in rows)


def signed_perms():
    """The 48 signed permutation matrices as functions on 3-vectors."""
    out = []
    for perm in itertools.permutations(range(3)):
        for signs in itertools.product((1, -1), repeat=3):
            out.append((perm, signs))
    return out


def apply_sp(sp, vec):
    """(perm, signs) applied to a 3-vector: new[i] = signs[i] * vec[perm[i]]."""
    perm, signs = sp
    return tuple(signs[ii] * vec[perm[ii]] for ii in range(3))


def dual_coords(basis, avec):
    """Coordinates of a' in the dual basis of Gamma, mod 1: (a'.r_1, a'.r_2, a'.r_3) mod 1."""
    return tuple((sum(aa * rr for aa, rr in zip(avec, row))) % 1 for row in basis)


def a_candidates(basis, cpts):
    """All classes a' mod Gamma* (as dual coordinates in [0,1)^3) with a'.z_j integral on an independent triple of cube points."""
    classes = set()
    for trip in itertools.combinations([pp for pp in cpts if any(pp)], 3):
        dd = det3(trip)
        if dd == 0:
            continue
        for cvec in itertools.product(range(abs(dd)), repeat=3):
            avec = solve3(trip, cvec)
            classes.add(dual_coords(basis, avec))
    classes.discard((Fr(0), Fr(0), Fr(0)))
    return classes


def a_from_dual(basis, dual):
    """The vector a' with a'.r_i = dual_i (exact)."""
    return solve3(basis, dual)


def box_points(basis, cpts, avec):
    """Lattice points (w, t) of the box: z in cube points, integer t with |t - a'.z| <= 1."""
    pts = []
    for zz in cpts:
        center = sum(aa * cc for aa, cc in zip(avec, zz))
        lo, hi = center - 1, center + 1
        for tt in range(int(lo) - 1, int(hi) + 2):
            if lo <= tt <= hi:
                ww = coords_in_basis(basis, zz)
                pts.append([ww[0], ww[1], ww[2], tt])
    return pts


def class_key(basis, avec, sps):
    """Canonical key of (Gamma, a') under B3 x {+-1}: min over images of (HNF of the image lattice, a' mod its dual)."""
    best = None
    for sp in sps:
        img_basis = hnf([apply_sp(sp, rr) for rr in basis])
        for sign in (1, -1):
            img_a = tuple(sign * xx for xx in apply_sp(sp, avec))
            key = (img_basis, dual_coords(img_basis, img_a))
            if best is None or key < best:
                best = key
    return best


def enumerate_boxes():
    """All box classes, as dicts."""
    sps = signed_perms()
    records, seen = [], set()
    for index in range(1, 7):
        for basis in hnf_bases(index):
            cpts = cube_points(basis)
            if not any(det3(trip) for trip in itertools.combinations(cpts, 3)):
                continue
            for dual in sorted(a_candidates(basis, cpts)):
                avec = a_from_dual(basis, dual)
                key = class_key(basis, avec, sps)
                if key in seen:
                    continue
                seen.add(key)
                pts = box_points(basis, cpts, avec)
                records.append({"index_d": index, "gamma_hnf_rows": [list(rr) for rr in basis],
                                "a_prime": [str(xx) for xx in avec], "G_box": len(pts), "points_wt": pts})
    return records


def run_tests():
    """d = 1 controls: the four boxes of N9/Q1 appear with G = 69, 67, 63, 63."""
    basis = ((1, 0, 0), (0, 1, 0), (0, 0, 1))
    cpts = cube_points(basis)
    for avec, want in (((Fr(1, 2), Fr(1, 2), 0), 69), ((Fr(1, 2),) * 3, 67), ((Fr(1, 3),) * 3, 63), ((Fr(1, 2), 0, 0), 63)):
        got = len(box_points(basis, cpts, avec))
        assert got == want, (avec, got, want)
    assert len(cube_points(basis)) == 27
    assert hnf(((0, 2, 0), (1, 1, 0), (0, 0, 3))) == ((2, 0, 0), (1, 1, 0), (0, 0, 3))  # (1,0,0) not in it; (2,0,0) is
    assert hnf(((1, 1, 0), (1, -1, 0), (0, 0, 1))) == ((2, 0, 0), (1, 1, 0), (0, 0, 1))  # D2 x Z: x1 + x2 even
    print("TESTS PASS (G of the four N9/Q1 boxes: 69, 67, 63, 63)")


def main_enumerate(out_path):
    """Write the box list (JSON lines) and print a summary table."""
    records = enumerate_boxes()
    with open(out_path, "w") as fh:
        for rec in records:
            fh.write(json.dumps(rec) + "\n")
    print(f"{len(records)} box classes written to {out_path}")
    for rec in records:
        print(f"  d={rec['index_d']} Gamma={rec['gamma_hnf_rows']} a'={rec['a_prime']} G_box={rec['G_box']}")


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--test", action="store_true")
    parser.add_argument("--out", type=Path)
    args = parser.parse_args()
    if args.test:
        run_tests()
    if args.out:
        main_enumerate(args.out)
    if not (args.test or args.out):
        sys.exit("give --test and/or --out FILE")


if __name__ == "__main__":
    main()
